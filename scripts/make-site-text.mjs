// The website's words, as one text file Grant Coach reads first.
//
// Grant Coach's first source is the public website — what NLA is, what it
// offers, how the day runs, the mission's words (Josh, 2026-10-23). The site
// is a React app built from this same repo, so a fetch of the live URL gets
// an empty shell; instead this script reads the public pages and sections
// and writes their visible text to src/lib/grantCoach/siteText.ts. It runs
// before every build (npm "prebuild"), so the snapshot never drifts from the
// site that is deployed. Run it by hand with `node scripts/make-site-text.mjs`.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n");

/** The public pages, in the order a visitor meets them. */
const PAGES = [
  ["Home", [
    "src/components/sections/HeroSection.tsx",
    "src/components/sections/FreeAccessMarquee.tsx",
    "src/components/sections/AboutSection.tsx",
    "src/components/sections/CoreValuesSection.tsx",
    "src/components/sections/ProgramsSection.tsx",
    "src/components/sections/ProgramsExtrasSection.tsx",
    "src/components/sections/DailyRhythmSection.tsx",
    "src/components/sections/MealTrainSection.tsx",
    "src/components/sections/MoreThanBoxingSection.tsx",
    "src/components/sections/ImpactStrip.tsx",
    "src/components/sections/ImpactSection.tsx",
    "src/components/sections/AwardsSection.tsx",
  ]],
  ["Programs", ["src/pages/Programs.tsx"]],
  ["Our Vision (The Launch Pad)", ["src/pages/Vision.tsx"]],
  ["Our Story", ["src/pages/OurStory.tsx"]],
  ["Meal Train", ["src/pages/MealTrain.tsx"]],
  ["Impact Story", ["src/pages/ImpactStory.tsx"]],
  ["Gym Buddies", ["src/pages/GymBuddies.tsx"]],
  ["Supporters", ["src/pages/Supporters.tsx"]],
];

const ENTITIES = { "&amp;": "&", "&rsquo;": "’", "&lsquo;": "‘", "&ldquo;": "“", "&rdquo;": "”", "&nbsp;": " ", "&mdash;": "—", "&ndash;": "–", "&hellip;": "…", "&apos;": "'", "&quot;": '"' };
const decode = (t) => t.replace(/&[a-z]+;/g, (e) => ENTITIES[e] ?? e).replace(/\{"\s*"\}|\{' '\}/g, " ").replace(/\s+/g, " ").trim();

/** Words a reader sees: JSX text and the string fields of the content objects. */
const FIELD = /\b(title|subtitle|description|desc|blurb|text|body|ageRange|ages|label|who|name|quote|time|policyText|caption|role|heading|value|tagline|detail)\s*:\s*(["'])((?:\\.|(?!\2)[^\\])*)\2/g;
const looksLikeCode = (t) =>
  t.length < 3 ||
  /=>|className|https?:\/\/|\bpx-|\bmd:|\btext-|\bbg-|\bflex\b|\bgrid\b|^[\d.%\s]+$|^[A-Za-z_]+\($|\$\{|^\w+=$/.test(t) ||
  /^[^A-Za-z]*$/.test(t);

const extract = (file) => {
  let src = read(file);
  src = src.replace(/^import[^\n]*\n/gm, "").replace(/\{\/\*[\s\S]*?\*\/\}/g, "").replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/[^\n]*$/gm, "");
  const out = [];
  const seen = new Set();
  const push = (t) => { const v = decode(t); if (!looksLikeCode(v) && !seen.has(v)) { seen.add(v); out.push(v); } };
  // Object fields first — they hold the cards, schedules and lists.
  for (const m of src.matchAll(FIELD)) push(m[3].replace(/\\(["'])/g, "$1"));
  // Then JSX text between tags, which may wrap over lines and hold inline tags.
  const stripped = src.replace(/<(strong|em|b|i|span|br)\b[^>]*\/?>/g, " ").replace(/<\/(strong|em|b|i|span)>/g, " ");
  for (const m of stripped.matchAll(/>\s*([^<>{}]*[A-Za-z][^<>{}]*?)\s*</g)) push(m[1]);
  return out;
};

const stamp = new Date().toLocaleDateString("en-CA", { timeZone: "America/New_York" });
const sections = PAGES.map(([page, files]) => {
  const lines = files.flatMap((f) => (fs.existsSync(path.join(ROOT, f)) ? extract(f) : []));
  return `## ${page}\n${lines.map((l) => `- ${l}`).join("\n")}`;
});
const text = `NO LIMITS ACADEMY — the public website (nolimitsboxingacademy.org), as published ${stamp}\n\n${sections.join("\n\n")}`;

const out = `// GENERATED by scripts/make-site-text.mjs — do not edit. The website's words,
// read by Grant Coach as its first source. Regenerated before every build.
export const SITE_TEXT_DATE = ${JSON.stringify(stamp)};
export const SITE_TEXT = ${JSON.stringify(text)};
`;
fs.writeFileSync(path.join(ROOT, "src/lib/grantCoach/siteText.ts"), out);
console.log(`siteText.ts: ${text.split("\n").length} lines, ${text.length} characters`);
